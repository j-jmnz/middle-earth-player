import { describe, expect, it } from "vitest";

import { bodyProblem } from "./commit-message.ts";
import { attributionLine, attributionMatch } from "./attribution.ts";

// A pull request's description becomes the squash commit's body, so it holds no attribution line (.claude/rules/commit-standards.md, Body).

describe("attribution lines", () => {
  it.each([
    `See https://claude.ai/${"code"}/session_01abc`,
    "co-authored-by: CLAUDE <noreply@anthropic.com>",
    "Co-Authored-By: Claude Opus <noreply@anthropic.com>",
    "Claude-Session: https://example.test/1",
    "claude-session: x",
  ])("finds %s", (line) => {
    expect(attributionLine(`What and why\n\n${line}\n`)).toBe(line);
  });

  it("passes a Generated by or Generated with Claude Code footer", () => {
    expect(attributionLine("_Generated by Claude Code_")).toBeUndefined();
    expect(attributionLine("🤖 Generated with [Claude Code](https://claude.com/claude-code)")).toBeUndefined();
  });

  it("finds none in an ordinary description, or a person's co-author line", () => {
    expect(attributionLine("## What and why\n\nAdd the Claude Code docs page.\n\nCo-Authored-By: Ann <ann@example.test>")).toBeUndefined();
    expect(attributionLine("")).toBeUndefined();
  });

  it("is read by the description check of commit:check", () => {
    expect(bodyProblem("## What and why\n\nCo-Authored-By: Claude <a@b.test>")).toContain("co-author");
    expect(bodyProblem("## What and why\n\nA plain description.")).toBeUndefined();
  });
  it("passes prose that names an attribution line", () => {
    expect(attributionLine("The check refuses a claude.ai/code link and a Claude-Session line.")).toBeUndefined();
    expect(attributionLine("`Claude-Session: x`")).toBeUndefined();
  });

  it("says which kind matched", () => {
    expect(attributionMatch("Claude-Session: x")?.kind).toBe("session");
    expect(attributionMatch("Co-Authored-By: Claude <a@b.test>")?.kind).toBe("co-author");
  });
});
